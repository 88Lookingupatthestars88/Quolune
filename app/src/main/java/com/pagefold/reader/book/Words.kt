    fun packOf(id: String): Pack? = packs.firstOrNull { it.id == id }

    /** 核心表 + 勾选的题材包 + 从书里抽出来的，合成一张；[off] 里的是用户点掉的，最后减掉。 */
    fun merge(
        packs: List<String>,
        extraVerbs: List<String>,
        extraAdvs: List<String>,
        extraTitles: List<String>,
        off: List<String> = emptyList(),
    ): Table {
        val drop = off.toSet()
        val v = LinkedHashSet(verbs)
        val t = LinkedHashSet(titles)
        val a = LinkedHashSet(advs)
        packs.forEach { id ->
            packOf(id)?.let {
                v.addAll(it.verbs); t.addAll(it.titles); a.addAll(it.advs)
            }
        }
        v.addAll(extraVerbs); t.addAll(extraTitles); a.addAll(extraAdvs)
        return Table(
            v.filter { it !in drop },
            t.filter { it !in drop },
            a.filter { it !in drop },
        )
    }

    data class Table(val verbs: List<String>, val titles: List<String>, val advs: List<String>)
